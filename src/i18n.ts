const DICTS: Record<Lang4, Dict> = { it, en, de, fr };

let current: Lang4 = "it";

export function setLang(lang: Lang4) {
  current = lang;
}

export function getLang(): Lang4 {
  return current;
}

/** Starting language inferred from the system (navigator.language). */
export function detectSystemLang(): Lang4 {
  const code = (navigator.language || "it").slice(0, 2).toLowerCase();
  return code === "en" || code === "de" || code === "fr" ? code : "it";
}

export function t(key: string, ...args: (string | number)[]): string {
  const dict = DICTS[current];
  let s = dict[key] ?? it[key] ?? key;
  args.forEach((a, i) => {
    s = s.replace(`{${i}}`, String(a));
  });
  return s;
}

